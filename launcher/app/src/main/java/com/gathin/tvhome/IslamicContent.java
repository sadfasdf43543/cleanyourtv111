    /** Alternates verses and hadith: even turns a verse, odd a hadith, walking each list in order from a seed. */
    static String[] pick(int turn, int seed) {
        boolean verse = turn % 2 == 0;
        String[][] list = verse ? VERSES : HADITH;
        int i = Math.floorMod(seed + turn / 2, list.length);
        String[] e = list[i];
        return new String[] {verse ? "\uFD3F " + e[0] + " \uFD3E" : "\u00AB" + e[0] + "\u00BB", e[1]};
    }
